/* eslint-env node */
/* Generates the standalone contract validators from the contract schemas:
   src/contract/validate.js from cypher-character.schema.json,
   src/contract/validateV3.js from cypher-character.schema.v3.json,
   src/contract/validateCreature.js from cypher-creature.schema.json, and
   src/contract/validateDropPayload.js from cypher-character.schema.json $defs/dropPayload.
   Run: npm run generate-validator (also runs automatically via prebuild). */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const here = path.dirname(fileURLToPath(import.meta.url))
/* The repo-root cypher-contract/ is the source of truth. The published sheet
   folder (Roll20/roll20-beacon-sheets) ships WITHOUT it — there each schema is
   vendored inside the sheet at ./cypher-contract/, and Roll20's CI (npm i +
   npm run build → prebuild → this script) must resolve that copy instead. */
const resolveSchemaPath = (file) => {
  const candidates = [
    path.resolve(here, `../../cypher-contract/${file}`),
    path.resolve(here, `../cypher-contract/${file}`)
  ]
  return candidates.find((p) => existsSync(p)) ?? candidates[0]
}

export const SCHEMA_PATH = resolveSchemaPath('cypher-character.schema.json')
export const OUT_PATH = path.resolve(here, '../src/contract/validate.js')
export const V3_SCHEMA_PATH = resolveSchemaPath('cypher-character.schema.v3.json')
export const V3_OUT_PATH = path.resolve(here, '../src/contract/validateV3.js')
export const CREATURE_SCHEMA_PATH = resolveSchemaPath('cypher-creature.schema.json')
export const CREATURE_OUT_PATH = path.resolve(here, '../src/contract/validateCreature.js')
export const DROP_PAYLOAD_OUT_PATH = path.resolve(here, '../src/contract/validateDropPayload.js')

/* Ajv standalone still emits CommonJS require() for its runtime helpers even
   with esm: true. Browsers have no require, so a raw emission crashes the
   production bundle before Vue mounts (vitest masks this — its transform
   pipeline shims CJS). Rewrite each `require("mod").default` into a real ESM
   import; the `.default ?? mod` fallback covers both Node and bundler interop
   shapes for the CJS helper modules. */
const toEsmImports = (code) => {
  const imports = []
  let n = 0
  const transformed = code.replace(/require\("([^"]+)"\)\.default/g, (_, mod) => {
    const name = `__ajvRuntime${n++}`
    imports.push(`import ${name} from "${mod}";`)
    return `(${name}.default ?? ${name})`
  })
  if (/\brequire\s*\(/.test(transformed)) {
    throw new Error('build-validator: unconverted require() in generated validator — emission shape changed')
  }
  return imports.join('') + transformed
}

// One generator for every contract schema: same Ajv settings, same ESM rewrite.
// `def` compiles one $defs entry instead of the root. It compiles a wrapper, never
// schema.$defs[def] itself, whose `#/$defs/...` references would then resolve against
// a root with no $defs and throw (spec ⑥ decision 7). The Python contract test wraps
// the same way (idml-to-roll20/tests/test_cypher_contract.py _payload_validator).
const generateSource = (schemaPath, { def } = {}) => {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
  const target = def ? { $defs: schema.$defs, $ref: `#/$defs/${def}` } : schema
  // verbose: errors carry .data (needed for enum messages); allErrors: report
  // every violation, not just the first (beacon-mapping §5.1 "first few violations").
  const ajv = new Ajv2020({ code: { source: true, esm: true }, verbose: true, allErrors: true })
  const validate = ajv.compile(target)
  const source = def ? `${path.basename(schemaPath)} $defs/${def}` : path.basename(schemaPath)
  const banner =
    `/* GENERATED by scripts/build-validator.mjs from cypher-contract/${source} — do not edit. */\n` +
    '/* eslint-disable */\n'
  return banner + toEsmImports(standaloneCode(ajv, validate))
}

export const generateValidatorSource = () => generateSource(SCHEMA_PATH)
export const generateV3ValidatorSource = () => generateSource(V3_SCHEMA_PATH)
export const generateCreatureValidatorSource = () => generateSource(CREATURE_SCHEMA_PATH)
export const generateDropPayloadValidatorSource = () => generateSource(SCHEMA_PATH, { def: 'dropPayload' })

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [
    [OUT_PATH, generateValidatorSource],
    [V3_OUT_PATH, generateV3ValidatorSource],
    [CREATURE_OUT_PATH, generateCreatureValidatorSource],
    [DROP_PAYLOAD_OUT_PATH, generateDropPayloadValidatorSource]
  ]
  for (const [outPath, generate] of outputs) {
    writeFileSync(outPath, generate())
    console.log(`wrote ${outPath}`)
  }
}
