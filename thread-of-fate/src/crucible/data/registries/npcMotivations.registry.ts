/**
 * NPC motivation registry for The Crucible - the "why" that sits underneath every
 * non-player character a Storyteller drops into a scene.
 *
 * Each entry pairs a want with the fear, flaw, secret, and contradiction that make it
 * playable, plus the levers a party can pull during a Social Encounter and a disposition
 * bias toward strangers. Authored for The Crucible following the "Detailed NPCs" guidance
 * in Convergence Storytelling Guide.md (Philosophy, Disposition, Reputation, Notable
 * Knowledge, Flaws or Secrets).
 */

export interface NpcMotivationDef {
  id: string;
  name: string;
  /** First-person statement of the want, e.g. 'I need the debt erased before it kills me.' */
  statement: string;
  /** What they fear will happen if they fail. */
  fear: string;
  /** The flaw that gets in their way. */
  flaw: string;
  /** A secret that plausibly accompanies this motivation. */
  secret: string;
  /** The internal contradiction that makes them interesting. */
  contradiction: string;
  /** What would make them abandon the goal. */
  breakingPoint: string;
  /** Levers a party can use in negotiation. */
  negotiationLevers: string[];
  /** Disposition bias toward strangers: -2..+2 */
  dispositionBias: number;
  category:
    | 'survival'
    | 'power'
    | 'love'
    | 'duty'
    | 'vengeance'
    | 'knowledge'
    | 'faith'
    | 'greed'
    | 'freedom'
    | 'redemption';
  keywords: string[];
  source: string;
}

