/**
 * NPC archetype registry for The Crucible - a Storyteller-facing cast list covering the
 * townsfolk, officials, crooks, clergy, and specialists a campaign actually runs on.
 *
 * Each entry is a starting point rather than a statblock: attribute emphasis, Talent
 * proficiencies, voice and mannerism seeds, notable knowledge, and gear, plus the creature
 * roles and Threat Rating to reach for on the rare occasion the NPC has to roll initiative.
 * Motivation ids point into npcMotivations.registry.ts.
 *
 * Source: authored for The Crucible following the "Quick NPCs" and "Detailed NPCs" guidance
 * in Convergence Storytelling Guide.md. Talent names match the 23 Convergence Talents.
 */

export interface NpcArchetypeDef {
  id: string;
  name: string;
  summary: string;
  occupation: string;
  /** Typical public-facing role. */
  publicRole: string;
  /** Suggested attribute emphasis, highest first (keys: might|instinct|focus|conviction|resonance|presence). */
  attributeEmphasis: ('might' | 'instinct' | 'focus' | 'conviction' | 'resonance' | 'presence')[];
  /** Talent ids/names this archetype is proficient in. */
  talents: string[];
  /** Suggested creature-role ids when the NPC needs combat stats. */
  combatRoleIds: string[];
  /** Suggested Threat Rating when statted for combat. */
  suggestedThreatRating: number;
  /** Motivation registry ids that fit. */
  motivationIds: string[];
  /** Voice/mannerism seeds. */
  voiceSeeds: string[];
  mannerismSeeds: string[];
  /** Things this archetype plausibly knows about. */
  knowledgeTopics: string[];
  /** Equipment they typically carry. */
  equipment: string[];
  keywords: string[];
  source: string;
}

