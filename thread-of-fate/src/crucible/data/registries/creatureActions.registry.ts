export const actionTemplateById: Record<string, CreatureActionTemplate> = Object.fromEntries(
  CREATURE_ACTIONS.map((x) => [x.id, x]),
);

/** All templates in one statblock section, in registry order. */
export function actionsForCategory(c: ActionCategory): CreatureActionTemplate[] {
  return CREATURE_ACTIONS.filter((action) => action.category === c);
}

/** Templates whose attack roll or damage rider keys off the given attribute. */
export function actionsForAttribute(attribute: AttributeKey): CreatureActionTemplate[] {
  return CREATURE_ACTIONS.filter((action) => {
    if (action.roll.type === 'attack' && action.roll.ability === attribute) return true;
    if ((action.damage ?? []).some((d) => d.abilityBonus === attribute)) return true;
    return (action.healing ?? []).some((h) => h.abilityBonus === attribute);
  });
}
