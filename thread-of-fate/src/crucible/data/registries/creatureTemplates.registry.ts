/**
 * Creature Template registry for The Crucible (Convergence GM entity-creation module).
 *
 * A creature template is a reusable overlay a GM stamps onto an existing statblock: it shifts
 * Threat Rating, nudges attribute scores, layers numeric modifiers onto entity dot paths, and
 * grants traits, actions, resistances, senses and tags. Templates are homebrew scaffolding for
 * the GM tool and stay deliberately plain so they stack predictably.
 *
 * Source: The Crucible.
 */

import type { ModifierDefinition } from '@/crucible/schemas/crucibleCommon';

export interface CreatureTemplateDef {
  id: string;
  name: string;
  description: string;
  /** Threat Rating delta applied when the template is used. */
  threatRatingDelta: number;
  /** Level delta, usually 0. */
  levelDelta: number;
  /** Attribute score deltas, keyed by might|instinct|focus|conviction|resonance|presence. */
  attributeDeltas: Partial<
    Record<'might' | 'instinct' | 'focus' | 'conviction' | 'resonance' | 'presence', number>
  >;
  /** Numeric modifiers applied to entity dot paths. */
  modifiers: ModifierDefinition[];
  /** Trait registry ids granted. */
  grantsTraitIds: string[];
  /** Action registry ids granted. */
  grantsActionIds: string[];
  addsResistances: string[];
  addsImmunities: string[];
  addsConditionImmunities: string[];
  addsVulnerabilities: string[];
  addsSenses: string[];
  /** Creature tag strings added to the printed line, e.g. 'Undead'. */
  addsTagNames: string[];
  /** Steps the size up (+1) or down (-1) the size ladder. */
  sizeSteps: number;
  /** Name pattern, e.g. '{{name}} the Hollowed' or 'Spectral {{name}}'. */
  namePattern: string;
  keywords: string[];
  source: string;
}

