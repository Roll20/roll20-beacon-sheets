/**
 * Creature Tags registry for The Crucible (GM entity creation).
 *
 * Every tag below is transcribed from the "Creature Tags" section of
 * `Convergence Bestiary.md` (lines 97-237) and its companion list `Creature Tags.md`.
 * Tags are the printed type line of a Convergence stat block (e.g. "Medium Humanoid (Any Race)");
 * `keywords` exist so the Crucible prompt parser can infer a tag from freeform GM text.
 * No tags are invented here, and the duplicate "Undead (Vampire)" entry is listed once.
 */

export interface CreatureTagDef {
  id: string;
  /** Printed form, e.g. "Humanoid (Any Race)". */
  name: string;
  /** Parent tag id for parenthesised subtypes; null for top-level tags. */
  parentId: string | null;
  /** Broad family used for filtering. */
  family:
    | 'humanoid'
    | 'beast'
    | 'undead'
    | 'construct'
    | 'celestial'
    | 'fiend'
    | 'fae'
    | 'dragon'
    | 'elemental'
    | 'flora'
    | 'plasmoid'
    | 'aberration'
    | 'giant'
    | 'divine'
    | 'social';
  /** Keywords the prompt parser matches to infer this tag. */
  keywords: string[];
  source: string;
}

