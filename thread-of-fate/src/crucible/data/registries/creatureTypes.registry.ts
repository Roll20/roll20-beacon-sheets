/**
 * Crucible registry of creature TYPES - the broad biological / metaphysical category a monster
 * belongs to, as distinct from the printed creature-tag string on its statblock line.
 * Each entry seeds sensible defaults (tags, resistances, senses, roles, origin, intelligence)
 * for the GM entity builder; every value remains editable on the generated block.
 *
 * Source: Convergence Bestiary.md (Creature Tags, lines 97-237) plus homebrew scaffolding for
 * the Crucible tool. Attributes are Might / Instinct / Focus / Conviction / Resonance / Presence,
 * saves are Body / Mind / Soul, magic is Artes powered by Aether, and large creatures may take
 * Apex Actions (legendary) or Overture Actions (mythic) on top of the standard 3 Action Points
 * and 1 Reaction.
 */

export interface CreatureTypeDef {
  id: string;
  name: string;
  description: string;
  /** Default creature-tag printed names (CreatureTagDef.name, not id) from creatureTags.registry. */
  defaultTagNames: string[];
  /** Typical damage resistances for this type. */
  typicalResistances: string[];
  /** Typical damage immunities. */
  typicalImmunities: string[];
  /** Typical condition immunities. */
  typicalConditionImmunities: string[];
  /** Senses entries, e.g. 'Darkvision 60 ft.' */
  typicalSenses: string[];
  /** Creature-role ids this type most often fills. */
  commonRoles: string[];
  /** Origin value for the monster block: natural | created | summoned | divine | eldritch | paracausal | machine | undead | unknown */
  defaultOrigin: string;
  /** mindless | animal | low | average | high | genius | cosmic */
  defaultIntelligence: string;
  keywords: string[];
  source: string;
}

